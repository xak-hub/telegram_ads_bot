def _extract_json(raw_text: str) -> dict:
    cleaned = raw_text.strip()
    cleaned = re.sub(r"^```(json)?", "", cleaned).strip()
    cleaned = re.sub(r"```$", "", cleaned).strip()
    return json.loads(cleaned)


def _is_transient(e: Exception) -> bool:
    # Битый JSON от модели случается иногда и обычно проходит со второго раза.
    if isinstance(e, json.JSONDecodeError):
        return True
    # Сетевые сбои и таймауты — временные.
    if isinstance(e, APITimeoutError):
        return True
    # APIResponseError — базовый класс сетевых ошибок (включая APIConnectionError,
    # который не экспортируется из zai.core, но является его подклассом).
    if isinstance(e, APIResponseError) and not isinstance(e, APIStatusError):
        return True
    # Рейт-лимит. Z.AI возвращает APIReachLimitError (HTTP 429) и для настоящего
    # превышения лимита (повторять стоит), и для нехватки средств/квоты на счету
    # (повторять бессмысленно — код 1113, "余额不足"/insufficient balance).
    # Второй случай пробрасываем сразу, без пустых ретраев.
    if isinstance(e, APIReachLimitError):
        message = str(e)
        if "1113" in message or "余额不足" in message or "insufficient" in message.lower():
            return False
        return True
    # Прочие ошибки со статус-кодом: повторяем только 5xx,
    # остальные клиентские 4xx (auth, неверный запрос) повторять бессмысленно.
    if isinstance(e, APIStatusError):
        status = getattr(e, "status_code", None)
        if status is not None:
            return status >= 500
    # Любая другая ошибка SDK — считаем временной, чтобы не падать на
    # незнакомых типах исключений (SDK может их добавить в будущем).
    if isinstance(e, ZaiError):
        return True
    return False


async def analyze_photo(images: list[tuple[bytes, str]], user_note: str) -> dict:
    content = []
    for i, (image_bytes, media_type) in enumerate(images, start=1):
        image_b64 = base64.standard_b64encode(image_bytes).decode("utf-8")
        content.append({"type": "text", "text": f"Изображение {i}:"})
        content.append({
            "type": "image_url",
            "image_url": {
                "url": f"data:{media_type};base64,{image_b64}",
            },
        })

    content.append({
        "type": "text",
        "text": (
            f"Подпись пользователя к фото: {user_note}"
            if user_note
            else "Пользователь не добавил подпись к фото."
        ),
    })

    async def _call():
        # zai-sdk предоставляет только синхронный клиент, поэтому запускаем
        # блокирующий HTTP-запрос в пуле потоков, чтобы не морозить event loop
        # aiogram на всё время обращения к GLM.
        response = await asyncio.to_thread(
            client.chat.completions.create,
            model=MODEL,
            max_tokens=2048,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": content},
            ],
        )
        raw_text = response.choices[0].message.content
        if not raw_text or not raw_text.strip():
            # Пустой ответ от GLM (часто бывает при rate limit / перегрузке).
            # Логируем и кидаем JSONDecodeError — он помечен как временный и
            # ретраится в retry_async.
            logger.warning("GLM вернул пустой ответ (rate limit/перегрузка) — ретрай")
            raise json.JSONDecodeError("Пустой ответ GLM", "", 0)
        return _extract_json(raw_text)

    # Больше попыток (5) и длиннее задержка — GLM регулярно отдаёт 429 (rate limit,
    # код 1302) на первый запрос, лимит отпускает через несколько секунд.
    return await retry_async(_call, retries=5, delay=4.0, is_transient=_is_transient)
